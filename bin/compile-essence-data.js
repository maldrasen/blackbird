// Usage: node bin/compile-essence-data.js
//
// Samples monster builds to estimate the essence range for every base monster, then writes the results to
// data/essence-data.js where the loader picks them up as global.EssenceData. This only needs to be rerun when monster
// data changes; the fixed seed keeps the output stable otherwise.

require('./run-headless.js');

const SAMPLES = 500;
const pad = ReportHelper.pad;
const padn = ReportHelper.padNumber;

Random.seed(666);

console.log("\n=== Compiling Essence Data ===\n")
console.log(pad('Monster',20) + padn('Level',6) + padn('Min',6) + padn('Avg',6) + padn('Max',6));
console.log(pad('-------',20) + padn('-----',6) + padn('---',6) + padn('---',6) + padn('---',6));

const rows = BaseMonster.getAllCodes().sort().map(code => {
  const base = BaseMonster.lookup(code);
  const values = [];

  for (let i=0; i<SAMPLES; i++) {
    values.push(EssenceSystem.monsterEssenceValue(MonsterFactory(code).build()));
  }

  const data = {
    code,
    level: base.getLevel(),
    min: Math.min(...values),
    max: Math.max(...values),
    average: Math.round(values.reduce((sum,value) => sum + value, 0) / SAMPLES),
  };

  console.log(pad(data.code,20) + padn(data.level,6) + padn(data.min,6) + padn(data.average,6) + padn(data.max,6));

  return data;
});

const entries = rows.map(row =>
  `  '${row.code}': { level:${row.level}, min:${row.min}, max:${row.max}, average:${row.average} },`);

fs.writeFileSync(`${ROOT}/data/essence-data.js`, `// Generated by bin/compile-essence-data.js — do not edit.

global.EssenceData = {
${entries.join('\n')}
};
`);

console.log(`\nWrote data/essence-data.js`);
